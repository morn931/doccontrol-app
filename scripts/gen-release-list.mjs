/**
 * Generate lib/carryover/released.ts from Ian's triage workbook.
 *
 *   node scripts/gen-release-list.mjs
 *
 * The released set is every row of the CDDL_Ian sheet whose "Action (Ian)" reads
 * "Proceed with new number". Nothing else is released — "Not recommeded - spec" keeps its
 * K038 number, "For discussion" is unresolved, and a BLANK action means the discipline has
 * not been reviewed at all (all 101 instrumentation documents are blank today).
 *
 * Re-run whenever engineering fills more of the Action column.
 */
import fs from 'node:fs'
import path from 'node:path'
import * as XLSX from 'xlsx'

for (const line of fs.readFileSync('.env.local','utf8').split(/\r?\n/)) {
  const t=line.trim(); if(!t||t.startsWith('#')||!t.includes('='))continue
  const i=t.indexOf('='); const k=t.slice(0,i).trim()
  if(!(k in process.env)) process.env[k]=t.slice(i+1).trim().replace(/^["']|["']$/g,'')
}
const LINK='https://ppetechcoza.sharepoint.com/:f:/s/PPEExternalSharing/IgA4KuVFDEQoSJvvGBPklyVnAb6YEjzVXRyXKensudYehkw?e=KkFNAI'
const shareId=(l)=>'u!'+Buffer.from(l,'utf8').toString('base64').replace(/\+/g,'-').replace(/\//g,'_').replace(/=+$/,'')
const retry=async(fn,n=4)=>{for(let i=0;;i++){try{return await fn()}catch(e){if(i>=n)throw e;await new Promise(r=>setTimeout(r,1500*(i+1)))}}}
const tok=(await retry(async()=>(await fetch(`https://login.microsoftonline.com/${process.env.MICROSOFT_TENANT_ID}/oauth2/v2.0/token`,{method:'POST',body:new URLSearchParams({client_id:process.env.MICROSOFT_CLIENT_ID,client_secret:process.env.MICROSOFT_CLIENT_SECRET,scope:'https://graph.microsoft.com/.default',grant_type:'client_credentials'})})).json())).access_token
const H={Authorization:`Bearer ${tok}`}
const root=await retry(async()=>(await fetch(`https://graph.microsoft.com/v1.0/shares/${shareId(LINK)}/driveItem`,{headers:H,cache:'no-store'})).json())
const drive=root.parentReference.driveId
const top=await retry(async()=>(await fetch(`https://graph.microsoft.com/v1.0/drives/${drive}/items/${root.id}/children?$top=999`,{headers:H})).json())
const file=(top.value??[]).find(c=>!c.folder&&/\.xlsx?$/i.test(c.name))
const buf=Buffer.from(await (await retry(async()=>fetch(file['@microsoft.graph.downloadUrl']))).arrayBuffer())
const aoa=XLSX.utils.sheet_to_json(XLSX.read(buf,{type:'buffer'}).Sheets['CDDL_Ian'],{header:1,defval:'',raw:false})
const S=(v)=>(v==null?'':String(v).trim())
const head=aoa[0].map(S)
const ACT=head.findIndex(h=>/^action/i.test(h)), RDMC=head.findIndex(h=>/rdmc document number/i.test(h)), DISC=head.findIndex(h=>/^discipline$/i.test(h))
// One row reads "Proceed  with new number" with a double space. Normalise, or it silently
// drops out of the release and one document stays hidden for no reason anybody can see.
const norm=(a)=>S(a).toLowerCase().replace(/\s+/g,' ')
const rows=aoa.slice(1).filter(r=>norm(r[ACT])==='proceed with new number')
const nums=[...new Set(rows.map(r=>S(r[RDMC])).filter(Boolean))].sort()
const byD={}; for(const r of rows){const d=S(r[DISC]).toUpperCase()||'?'; byD[d]=(byD[d]||0)+1}
const out=path.join(process.cwd(),'lib/carryover/released.ts')
fs.writeFileSync(out,`// ─────────────────────────────────────────────────────────────────────────────
// RELEASED FOR RENUMBERING — the documents engineering has actually signed off.
//
// GENERATED by scripts/gen-release-list.mjs from "${file.name}",
// sheet CDDL_Ian, column "Action (Ian)" = "Proceed with new number".
// Saved ${String(file.lastModifiedDateTime).slice(0,16).replace('T',' ')} by ${file.lastModifiedBy?.user?.displayName ?? '?'}. Do not hand-edit.
//
// ⚠️ NOTHING ELSE IS RELEASED, and the reasons differ:
//   · "Not recommeded - spec" — keeps its K038 number, must NOT be renumbered;
//   · "For discussion"        — unresolved;
//   · BLANK                   — the discipline has not been reviewed at all. Every one of
//                               the 101 instrumentation documents is blank today.
// A blank action is not a "no". It means nobody has looked, which is why these are hidden
// rather than shown as rejected.
//
// Discipline split of this release: ${Object.entries(byD).map(([k,v])=>`${k} ${v}`).join(' · ')}.
// Re-run the generator when engineering fills in more of the Action column.
// ─────────────────────────────────────────────────────────────────────────────

/** Document numbers engineering has released, exactly as written in the workbook. */
export const RELEASED_DOCNOS: string[] = [
${nums.map(n=>`  '${n}',`).join('\n')}
]

export const RELEASE_SOURCE = ${JSON.stringify(file.name)}
export const RELEASE_SAVED_AT = ${JSON.stringify(String(file.lastModifiedDateTime).slice(0,16).replace('T',' '))}
`,'utf8')
console.log(`released rows: ${rows.length}   distinct numbers: ${nums.length}`)
console.log(`by discipline: ${Object.entries(byD).map(([k,v])=>`${k} ${v}`).join(' · ')}`)
console.log(`written: ${path.relative(process.cwd(),out)}`)
